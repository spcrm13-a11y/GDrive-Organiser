#!/usr/bin/env python3
"""Regenerate ainie-knowfind's .env from Infisical. Run on theguardian.

Values go Infisical -> ./.env (mode 0600) -> container environment and are
never printed: this prints only key names and a count, so a transcript of a
deploy carries no secret material.

Secrets live in the Infisical project `ainie-spdesk`, env `prod`, reached with
that project's machine identity at ~/.infisical-spdesk-credentials.json.
GEMINI_API_KEY was already there; the knowfind keys were added alongside it
rather than copied into a second store. See versions.md 26.10.15-001.

Values are written WITHOUT surrounding quotes on purpose. Compose's own dotenv
parser strips one matching pair of quotes from a value, and a hand-rolled
reader that does not strip them silently includes the quote characters -- on
2026-09-12 that produced a 34-character "password" (two stray quotes around a
32-character value) and overwrote a live database role with it.
"""
import json
import os
import pathlib
import urllib.parse
import urllib.request

CREDS = pathlib.Path.home() / ".infisical-spdesk-credentials.json"
ENV_PATH = pathlib.Path(__file__).resolve().parent.parent / ".env"

# env var in .env  ->  secret key in Infisical
SECRETS = {
    "GEMINI_API_KEY": "GEMINI_API_KEY",
    "MQTT_PASSWORD": "SMARTPLANET_MQTT_PASSWORD",
    "TS_AUTHKEY": "KNOWFIND_TS_AUTHKEY",
    "AUTHENTIK_TOKEN": "KNOWFIND_AUTHENTIK_TOKEN",
}

# Not secret: the deployment's own shape. Kept here rather than in Infisical so
# a reader can see where this app lives without holding credentials.
PLAIN = {
    "NODE_ENV": "production",
    "PORT": "3000",
    "APP_URL": "https://knowfind.tail2227aa.ts.net",
    "MQTT_HOST": "100.102.174.92",
    "MQTT_PORT": "1883",
    "MQTT_USER": "smartplanet",
    "AUTHENTIK_HOST": "http://authentik-server-1:9000",
    # The Authentik login host, not this app's host -- see docker-compose.yml.
    "AUTHENTIK_HOST_BROWSER": "https://theguardian.tail2227aa.ts.net",
}


def main() -> None:
    creds = json.loads(CREDS.read_text())
    api = creds["apiUrl"].rstrip("/")
    project = creds["projectId"]
    environment = creds.get("environment", "prod")

    req = urllib.request.Request(
        f"{api}/v1/auth/universal-auth/login",
        data=json.dumps(
            {"clientId": creds["clientId"], "clientSecret": creds["clientSecret"]}
        ).encode(),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    token = json.load(urllib.request.urlopen(req, timeout=25))["accessToken"]

    query = urllib.parse.urlencode(
        {"workspaceId": project, "environment": environment, "secretPath": "/"}
    )
    req = urllib.request.Request(
        f"{api}/v3/secrets/raw?{query}", headers={"Authorization": f"Bearer {token}"}
    )
    fetched = {
        s["secretKey"]: s["secretValue"]
        for s in json.load(urllib.request.urlopen(req, timeout=25)).get("secrets", [])
    }

    missing = [k for k in SECRETS.values() if not fetched.get(k, "").strip()]
    if missing:
        raise SystemExit(
            "x missing or empty in Infisical ainie-spdesk/"
            f"{environment}: {', '.join(missing)}\n"
            "  Add them there first -- do not hand-write them into .env."
        )

    lines = ["# GENERATED by deploy/write-env.py from Infisical. Do not edit."]
    lines += [f"{k}={v}" for k, v in PLAIN.items()]
    lines += [f"{env}={fetched[key].strip()}" for env, key in SECRETS.items()]

    # Written via a 0600 temp file in the same directory, then renamed, so the
    # secrets are never briefly world-readable and a failed write cannot leave
    # a half-written .env behind.
    tmp = ENV_PATH.with_suffix(".env.tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    os.replace(tmp, ENV_PATH)

    print(f"  wrote {ENV_PATH} with {len(PLAIN) + len(SECRETS)} keys:")
    print("    from Infisical:", ", ".join(sorted(SECRETS)))
    print("    plain config  :", ", ".join(sorted(PLAIN)))


if __name__ == "__main__":
    main()
